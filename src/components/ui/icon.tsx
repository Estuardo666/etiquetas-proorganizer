export function Icon({
  name,
  className,
  strokeWidth = 1.8,
  style,
}: {
  name: string;
  className?: string;
  strokeWidth?: number;
  style?: React.CSSProperties;
}) {
  const Cmp = map[name] ?? Sparkles;
  return (
    <Cmp className={className} strokeWidth={strokeWidth} style={style} aria-hidden="true" />
  );
}

